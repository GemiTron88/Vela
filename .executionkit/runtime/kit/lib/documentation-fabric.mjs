function ensureOutputRoot(root,rel){
  const full=resolveProjectPathSafe(root,rel,'documentation output root',{createParents:true});
  if(fs.existsSync(full)){
    const stat=fs.lstatSync(full);
    if(stat.isSymbolicLink()||!stat.isDirectory())throw new Error('Documentation output root must be a real project-local directory');
  } else fs.mkdirSync(full,{recursive:true});
  return full;
}
function safeGeneratedWrite(file,content){
  if(fs.existsSync(file)){
    const stat=fs.lstatSync(file);
    if(stat.isSymbolicLink()||!stat.isFile())throw new Error(`Documentation target is unsafe: ${file}`);
    const existing=fs.readFileSync(file,'utf8');
    if(!existing.startsWith(GENERATED_MARKER))throw new Error(`Refusing to overwrite non-generated documentation: ${file}`);
  }
  const tmp=`${file}.tmp-${process.pid}-${Date.now()}`;
  fs.writeFileSync(tmp,content,{mode:0o644});
  fs.renameSync(tmp,file);
}
export function writeDocumentationFabric(root,options={}){
  const compiled=compileDocumentationFabric(root,options),out=ensureOutputRoot(root,compiled.config.outputRoot);
  for(const d of compiled.documents)safeGeneratedWrite(path.join(out,d.file),d.content);
  safeGeneratedWrite(path.join(out,'INDEX.md'),compiled.index);
  const registryPath=resolveDerivedPath(root,compiled.config.registryPath,'documentation registry',{createParents:true});
  fs.mkdirSync(path.dirname(registryPath),{recursive:true});
  const tmp=`${registryPath}.tmp-${process.pid}-${Date.now()}`;
  fs.writeFileSync(tmp,JSON.stringify(compiled.registry,null,2)+'\n',{mode:0o600});
  fs.renameSync(tmp,registryPath);
  return {status:'BUILT',registry:compiled.registry,outputRoot:compiled.config.outputRoot,registryPath:compiled.config.registryPath};
}
export function validateDocumentationFabric(root,options={}){
  const compiled=compileDocumentationFabric(root,options),errors=[],out=resolveProjectPathSafe(root,compiled.config.outputRoot,'documentation output root');
  for(const d of compiled.documents){
    const file=path.join(out,d.file);
    if(!fs.existsSync(file)){errors.push({code:'DOC_MISSING',path:posix(path.relative(root,file)),documentId:d.id});continue;}
    const stat=fs.lstatSync(file);
    if(stat.isSymbolicLink()||!stat.isFile()){errors.push({code:'DOC_UNSAFE',path:posix(path.relative(root,file)),documentId:d.id});continue;}
    const actual=fs.readFileSync(file,'utf8').replaceAll('\r\n','\n');
    if(actual!==d.content)errors.push({code:'DOC_STALE',path:posix(path.relative(root,file)),documentId:d.id,expectedFingerprint:d.fingerprint,actualFingerprint:sha(actual)});
  }
  const indexFile=path.join(out,'INDEX.md');
  if(!fs.existsSync(indexFile))errors.push({code:'DOC_INDEX_MISSING',path:posix(path.relative(root,indexFile))});
  else if(fs.readFileSync(indexFile,'utf8').replaceAll('\r\n','\n')!==compiled.index)errors.push({code:'DOC_INDEX_STALE',path:posix(path.relative(root,indexFile))});
  const registryFile=resolveDerivedPath(root,compiled.config.registryPath,'documentation registry');
  if(!fs.existsSync(registryFile))errors.push({code:'DOC_REGISTRY_MISSING',path:compiled.config.registryPath});
  else{
    try{
      const onDiskReg=JSON.parse(fs.readFileSync(registryFile,'utf8'));
      if(onDiskReg?.schemaVersion!=='documentation-fabric-registry/v1')errors.push({code:'DOC_REGISTRY_INVALID',path:compiled.config.registryPath});
      else if(onDiskReg.engineeringKnowledgeFingerprint!==compiled.registry.engineeringKnowledgeFingerprint||(onDiskReg.sourcePackFingerprint&&onDiskReg.sourcePackFingerprint!==compiled.registry.sourcePackFingerprint))errors.push({code:'DOC_REGISTRY_STALE',path:compiled.config.registryPath});
    }catch{errors.push({code:'DOC_REGISTRY_INVALID',path:compiled.config.registryPath});}
  }
  if(!compiled.registry.coverage.pass)errors.push({code:'DOC_COVERAGE_INCOMPLETE',coverage:compiled.registry.coverage});
  return {schemaVersion:'documentation-fabric-validation/v1',status:errors.length?'FAIL':'PASS',ok:errors.length===0,errors,registry:compiled.registry};
}
export function documentationFabricStatus(root,options={}){
  const cfg=readConfig(root);
  if(cfg.enabled!==true)return {schemaVersion:'documentation-fabric-status/v1',status:'DISABLED',enabled:false};
  const validation=validateDocumentationFabric(root,options);
  return {schemaVersion:'documentation-fabric-status/v1',enabled:true,status:validation.ok?'CURRENT':'STALE_OR_MISSING',ok:validation.ok,coverage:validation.registry.coverage,errors:validation.errors,repository:validation.registry.repository,outputRoot:cfg.outputRoot};
}
export function searchDocumentationFabric(root,query,{limit=20}={}){
  if(typeof query!=='string'||!query.trim())throw new Error('Documentation search query is required');
  if(!Number.isInteger(limit)||limit<1||limit>100)throw new Error('Documentation search limit must be 1..100');
  const cfg=readConfig(root);
  if(cfg.enabled!==true)throw new Error('Documentation Fabric is disabled');
  const out=resolveProjectPathSafe(root,cfg.outputRoot,'documentation output root'),needle=query.toLowerCase(),hits=[];
  const allPresentOnDisk=REQUIRED_DOCUMENTATION_IDS.every((id)=>fs.existsSync(path.join(out,`${id}.md`)));
  const docs=allPresentOnDisk
    ? REQUIRED_DOCUMENTATION_IDS.map((id)=>({id,file:`${id}.md`,content:fs.readFileSync(path.join(out,`${id}.md`),'utf8')}))
    : compileDocumentationFabric(root).documents;
  for(const d of docs){
    const diskFile=path.join(out,d.file);
    let content=d.content;
    if(!allPresentOnDisk&&fs.existsSync(diskFile)){try{content=fs.readFileSync(diskFile,'utf8');}catch{}}
    const lines=content.split(/\r?\n/);
    for(let i=0;i<lines.length;i++){
      const col=lines[i].toLowerCase().indexOf(needle);if(col<0)continue;
      hits.push({documentId:d.id,file:`${cfg.outputRoot}/${d.file}`,line:i+1,column:col+1,snippet:lines.slice(Math.max(0,i-1),Math.min(lines.length,i+2)).join('\n'),fingerprint:sha(content.replaceAll('\r\n','\n'))});
      if(hits.length>=limit)return {schemaVersion:'documentation-fabric-search/v1',query,hits};
    }
  }
  return {schemaVersion:'documentation-fabric-search/v1',query,hits};
}
