const GENERATED_MARKER='<!-- GENERATED:AI-EXECUTIONKIT-DOCUMENTATION-FABRIC -->';
const sha=(value)=>crypto.createHash('sha256').update(value).digest('hex');
const posix=(value)=>String(value).replaceAll('\\','/');
const uniq=(items)=>[...new Set(items.filter(Boolean))].sort();

export const DEFAULT_DOCUMENTATION_CONFIG=Object.freeze({
  enabled:true,
  outputRoot:'docs/knowledge-base/generated',
  registryPath:'.executionkit/knowledge/documentation-registry.json',
  requiredForRelease:true,
  minimumCoveragePercent:100,
});

export const REQUIRED_DOCUMENTATION_IDS=Object.freeze([
  'overview','architecture','components','domains','features','business-rules','workflows','events-jobs',
  'interfaces','data','auth-permissions','integrations','configuration','storage','search-cache',
  'notifications','payments','security','testing','deployment','operations','decisions','known-limitations','glossary',
]);

function readConfig(root){
  const file=path.join(path.resolve(root),'execution.config.json');
  if(!fs.existsSync(file))return {...DEFAULT_DOCUMENTATION_CONFIG,proofRoot:'docs/execution/evidence/tasks'};
  const config=JSON.parse(fs.readFileSync(file,'utf8'));
  return {...DEFAULT_DOCUMENTATION_CONFIG,...(config.documentation??{}),proofRoot:config.evidence?.taskProofRoot??config.evidence?.proofRoot??'docs/execution/evidence/tasks'};
}
function sourceRefs(section){return uniq(section?.sourceRefs??[]);}
function allRefs(...sections){return uniq(sections.flatMap(sourceRefs));}
function renderList(items){
  if(!items?.length)return '- None detected from current source.';
  return items.map((item)=>`- ${typeof item==='string'?item:`\`${JSON.stringify(item)}\``}`).join('\n');
}
function header(title,artifact,documentId,refs){
  const sourceFingerprint=sha(JSON.stringify(refs.map((p)=>({path:p}))));
  return [
    GENERATED_MARKER,
    `# ${title}`,'',
    '> Generated by AI ExecutionKit Documentation & Knowledge Fabric. This is source-grounded derived knowledge; live source, canonical TODO and runtime evidence win on conflict.','',
    `- Document ID: \`${documentId}\``,
    `- Knowledge fingerprint: \`${artifact.inputFingerprints?.find((x)=>x.kind==='section-map')?.value??'UNAVAILABLE'}\``,
    `- Source-reference fingerprint: \`${sourceFingerprint}\``,'',
  ].join('\n');
}
function refsBlock(refs){
  return ['## Source references','',...(refs.length?refs.map((p)=>`- \`${p}\``):['- None detected.']),''].join('\n');
}
function doc(title,id,artifact,sections,body,extraRefs=[]){
  const refs=uniq([...allRefs(...sections),...extraRefs]);
  const content=[header(title,artifact,id,refs),body,'',refsBlock(refs)].join('\n').trimEnd()+'\n';
  return {id,title,file:`${id}.md`,content,sourceRefs:refs,fingerprint:sha(content)};
}
function signalPaths(pack,re,max=160){return pack.files.map((f)=>f.path).filter((p)=>re.test(p)).slice(0,max);}
function securitySignals(pack){
  const re=/(auth|authorization|permission|policy|guard|middleware|csrf|cors|security|saniti[sz]|encrypt|hash|secret|oauth|passkey|biometric|tenant)/i;
  return signalPaths(pack,re,140);
}
function operationsSignals(pack){
  const re=/(health|readiness|metrics|logging|logger|observability|monitor|queue|worker|scheduler|cron|supervisor|systemd|horizon|reverb|redis|opensearch|clickhouse|nginx|caddy|docker|deploy|infra)/i;
  return pack.files.map((f)=>f.path).filter((p)=>re.test(p)).slice(0,140);
}
function glossaryTerms(sections){
  const out=[];
  for(const item of sections.domains?.items??[]) if(item?.name)out.push({term:item.name,evidence:item.path??null,classification:item.classification??'domain-candidate'});
  for(const item of sections.integrations?.items??[]) if(item?.name)out.push({term:item.name,evidence:item.ecosystem??null,classification:'dependency/integration'});
  return out.slice(0,200);
}
